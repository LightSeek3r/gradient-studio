#!/usr/bin/env python3
"""Generate ``src/opal42_gradient/_names_table.py`` from the TypeScript reference.

The 148 CSS named colours are read from ``CSS_NAMED_COLORS`` in
``packages/core/src/color-formats.ts`` (insertion order is preserved: the
nearest-name lookup keeps the *first* name for each hex, so aliases resolve to
``aqua`` over ``cyan`` and ``gray`` over ``grey``).  Nothing is typed by hand.

    python3 scripts/gen_names.py            # rewrite the generated module
    python3 scripts/gen_names.py --check    # exit 1 if the module is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[1]
SOURCE = REPO / "packages" / "core" / "src" / "color-formats.ts"
TARGET = ROOT / "src" / "opal42_gradient" / "_names_table.py"

_BLOCK = re.compile(r"export const CSS_NAMED_COLORS: Record<string, string> = \{(.*?)^\};", re.S | re.M)
_ENTRY = re.compile(r'^\s*([a-z]+): "(#[0-9a-f]{6})",\s*$')


def read_table(source: Path = SOURCE) -> list[tuple[str, str]]:
    match = _BLOCK.search(source.read_text(encoding="utf-8"))
    if match is None:
        raise SystemExit(f"CSS_NAMED_COLORS not found in {source}")
    entries: list[tuple[str, str]] = []
    for line in match.group(1).splitlines():
        if not line.strip():
            continue
        entry = _ENTRY.match(line)
        if entry is None:
            raise SystemExit(f"unrecognised line in CSS_NAMED_COLORS: {line!r}")
        entries.append((entry.group(1), entry.group(2)))
    if len({name for name, _ in entries}) != len(entries):
        raise SystemExit("duplicate colour name in the reference table")
    return entries


def render(entries: list[tuple[str, str]]) -> str:
    return (
        '"""The CSS named colours. GENERATED by scripts/gen_names.py - do not edit.\n\n'
        "Source: ``CSS_NAMED_COLORS`` in packages/core/src/color-formats.ts "
        f"({len(entries)} names, reference insertion order).\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        "from types import MappingProxyType\n"
        "from typing import Final\n\n"
        "CSS_NAMED_COLORS: Final = MappingProxyType(\n"
        "    {\n"
        + "".join(f'        "{name}": "{hex_}",\n' for name, hex_ in entries)
        + "    }\n"
        ")\n"
        '"""name -> ``#rrggbb`` (read-only, reference insertion order)."""\n\n'
        'CSS_COLOR_NAMES: Final = tuple(CSS_NAMED_COLORS)\n'
        '"""The names in reference order."""\n'
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the generated module is out of date")
    args = parser.parse_args()
    text = render(read_table())
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET} is out of date; run scripts/gen_names.py", file=sys.stderr)
            return 1
        print(f"{TARGET.name} is up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
