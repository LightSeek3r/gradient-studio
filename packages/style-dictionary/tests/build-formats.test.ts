/* eslint-disable @typescript-eslint/no-explicit-any -- test fixtures read untyped JSON */
import { afterEach, describe, expect, it } from "vitest";
import { build, type BuildResult } from "./helpers";
import { NAVY_STOPS, RGB_STOPS, SMOOTH_STOPS, srgb, stop } from "./fixtures";

let last: BuildResult | undefined;
afterEach(async () => {
  await last?.cleanup();
  last = undefined;
});
const run = async (tokens: unknown, extra = {}) => (last = await build({ tokens: { "t.json": tokens }, ...extra }));

const MIXED = {
  color: { brand: { $type: "color", $value: srgb(0.0627, 0.1059, 0.2706) }, accent: { $type: "color", $value: srgb(0.5765, 0.2, 0.9176) } },
  size: { small: { $type: "dimension", $value: { value: 4, unit: "px" } } },
  gradient: {
    $type: "gradient",
    smooth: { $value: SMOOTH_STOPS },
    rainbow: { $value: RGB_STOPS, $description: "three saturated primaries" },
    navy: { $value: NAVY_STOPS, $extensions: { "io.github.lightseek3r.gradient-studio": { angle: 135 } } },
    ref: { $value: [{ color: "{color.brand}", position: 0 }, { color: "{color.accent}", position: 1 }] },
    legacy: { $value: "linear-gradient(180deg, #101b45 0%, #9333ea 100%)" },
    translucent: { $value: [{ color: srgb(1, 0, 0, 0.5), position: 0 }, stop("#0000ff", 1)] },
    broken: { $value: "oops" },
    stripes: { $value: [stop("#ff0000", 0), stop("#ff0000", 0.5), stop("#0000ff", 0.5), stop("#0000ff", 1)] },
    locked: { $value: RGB_STOPS, $extensions: { opal42: { lock: true } } },
  },
};

describe("opal42/css-gradients", () => {
  it("prints custom properties for every gradient token, in token order, nothing else", async () => {
    const r = await run(MIXED);
    expect(await r.read("gradients.css")).toBe(
      [
        "/* Generated by @opal42/style-dictionary. */",
        ":root {",
        "  --gradient-smooth: linear-gradient(90deg, #101b45 0%, #9333ea 100%);",
        "  --gradient-rainbow: linear-gradient(90deg, #ff0000 0%, #00ff00 50%, #0000ff 100%);",
        "  --gradient-navy: linear-gradient(135deg, #101b45 0%, #eeeeee 30%, #202040 100%);",
        "  --gradient-ref: linear-gradient(90deg, #101b45 0%, #9333ea 100%);",
        "  --gradient-legacy: linear-gradient(180deg, #101b45 0%, #9333ea 100%);",
        "  --gradient-translucent: linear-gradient(90deg, rgb(255 0 0 / 0.5) 0%, #0000ff 100%);",
        "  /* skipped gradient-broken: no-gradient */",
        "  --gradient-stripes: linear-gradient(90deg, #ff0000 0%, #ff0000 50%, #0000ff 50%, #0000ff 100%);",
        "  --gradient-locked: linear-gradient(90deg, #ff0000 0%, #00ff00 50%, #0000ff 100%);",
        "}",
        "",
      ].join("\n"),
    );
  });

  it("honours file.options.selector", async () => {
    const r = await run({ g: { $type: "gradient", $value: SMOOTH_STOPS } }, { files: [{ destination: "g.css", format: "opal42/css-gradients", options: { selector: ".theme-dark" } }] });
    expect((await r.read("g.css")).split("\n")[1]).toBe(".theme-dark {");
  });

  it("an empty dictionary gives an empty rule", async () => {
    const r = await run({ n: { $type: "number", $value: 1 } });
    expect(await r.read("gradients.css")).toBe("/* Generated by @opal42/style-dictionary. */\n:root {\n}\n");
  });

  it("uses the angle option for tokens that carry none", async () => {
    const r = await run({ g: { $type: "gradient", $value: SMOOTH_STOPS } }, { options: { angle: 45 } });
    expect(await r.read("gradients.css")).toContain("linear-gradient(45deg,");
  });

  it("is byte-identical across two builds", async () => {
    const a = await build({ tokens: { "t.json": MIXED } });
    const b = await build({ tokens: { "t.json": MIXED } });
    expect(await a.read("gradients.css")).toBe(await b.read("gradients.css"));
    expect(await a.read("report.json")).toBe(await b.read("report.json"));
    await a.cleanup();
    await b.cleanup();
  });
});

describe("opal42/report-json", () => {
  it("summarises every gradient token (snapshot)", async () => {
    const r = await run(MIXED);
    expect(await r.read("report.json")).toMatchSnapshot();
  });

  it("is sorted by path and counts statuses", async () => {
    const rep = await (await run(MIXED)).json("report.json");
    expect(rep.tokens.map((t: any) => t.path)).toEqual([...rep.tokens.map((t: any) => t.path)].sort());
    expect(rep.summary).toEqual({ gradients: 9, scored: 7, unscorable: 1, skipped: 1 });
    expect(rep.scoringModel).toBe("v1");
    expect(rep.note).toMatch(/not a quality verdict/);
    expect(rep).not.toHaveProperty("minScore");
  });

  it("includes minScore only when the option is set", async () => {
    const rep = await (await run(MIXED, { options: { minScore: 10 } })).json("report.json");
    expect(rep.minScore).toBe(10);
  });

  it("contains no absolute paths or timestamps", async () => {
    const r = await run(MIXED);
    const text = await r.read("report.json");
    expect(text).not.toContain(r.dir);
    expect(text).not.toMatch(/20\d\d-\d\d-\d\d/);
  });

  it("lists unscorable and skipped tokens with their codes", async () => {
    const rep = await (await run(MIXED)).json("report.json");
    const by = Object.fromEntries(rep.tokens.map((t: any) => [t.path, t]));
    expect(by["gradient.translucent"]).toMatchObject({ status: "unscorable", code: "alpha", score: null });
    expect(by["gradient.broken"]).toMatchObject({ status: "skipped", code: "no-gradient", score: null });
    expect(by["gradient.locked"].locked).toBe(true);
  });
});
